import { useCallback, useMemo } from "react";
import { StyleSheet, View } from "react-native";
import * as Haptics from "expo-haptics";
import { StatusBar } from "expo-status-bar";
import { useLocalSearchParams, useRouter } from "expo-router";
import { WebView, type WebViewMessageEvent } from "react-native-webview";
import { LESSONS_HTML } from "@/lib/interactive/lessonsHtml";
import { closerPage, useCloserPage } from "@/state/closerPage";

/**
 * A Closer lesson, full screen. Every lesson (stories, studies, cases, books, threads, psalms…) is the Page prototype
 * itself, built as one offline page (lib/interactive/lessonsHtml.ts, generated by closer-page `npm run app`). The app
 * tells the page which lesson to play and what's already saved; the page tells the app when the lesson is finished,
 * when a verse or note is kept, when to tap a haptic, and when to close.
 */
export default function LessonScreen() {
  const router = useRouter();
  const { id } = useLocalSearchParams<{ id: string }>();
  const { verses, settings } = useCloserPage();
  // set once, before the page loads; later changes come back to us as messages
  const boot = useMemo(
    () => `window.__CLOSER_APP__=${JSON.stringify({ lesson: id, saved: verses.map(v => v.ref), largeText: settings.largeText, reduceMotion: settings.reduceMotion })};true;`,
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [id],
  );
  const onMessage = useCallback((e: WebViewMessageEvent) => {
    let msg: { type?: string; [k: string]: unknown };
    try { msg = JSON.parse(e.nativeEvent.data); } catch { return; }
    switch (msg.type) {
      case "close": router.back(); break;
      case "finished": closerPage.finish(String(msg.id)); break;
      case "verse": closerPage.saveVerse(msg.verse as never, !!msg.saved); break;
      case "note": closerPage.keepNote(msg.note as never); break;
      case "haptic":
        if (msg.style === "success") void Haptics.notificationAsync(Haptics.NotificationFeedbackType.Success);
        else void Haptics.impactAsync(msg.style === "medium" ? Haptics.ImpactFeedbackStyle.Medium : Haptics.ImpactFeedbackStyle.Light);
        break;
    }
  }, [router]);
  return (
    <View style={styles.root}>
      <StatusBar style="auto" />
      <WebView
        source={{ html: LESSONS_HTML, baseUrl: "https://closer.app/lessons/" }}
        injectedJavaScriptBeforeContentLoaded={boot}
        originWhitelist={["*"]}
        onMessage={onMessage}
        style={styles.web}
        containerStyle={styles.web}
        contentInsetAdjustmentBehavior="never"
        automaticallyAdjustContentInsets={false}
        scrollEnabled={false}
        bounces={false}
        overScrollMode="never"
        javaScriptEnabled
        setSupportMultipleWindows={false}
        allowsBackForwardNavigationGestures={false}
        hideKeyboardAccessoryView
        keyboardDisplayRequiresUserAction={false}
        accessibilityLabel="Lesson"
      />
    </View>
  );
}

const styles = StyleSheet.create({
  root: { flex: 1, backgroundColor: "#FFF7EB" },
  web: { flex: 1, backgroundColor: "#FFF7EB" },
});
