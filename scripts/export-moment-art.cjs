// Export the prototype's unchanged illustrations for native image caching.
const fs = require('fs');
const ts = require('typescript');
const vm = require('vm');
const exportsObject = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('constants/readerMomentArt.ts', 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS },
}).outputText, { exports: exportsObject });
fs.mkdirSync('assets/moment-placeholders', { recursive: true });
const names = Object.keys(exportsObject.READER_MOMENT_ART);
for (const name of names) {
  fs.writeFileSync(`assets/moment-placeholders/${name}.svg`, exportsObject.READER_MOMENT_ART[name].replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" width="320" height="220" ') + '\n');
}
fs.writeFileSync('constants/momentArtSources.ts', '// Generated by scripts/export-moment-art.cjs\nexport const MOMENT_ART_SOURCES = {\n' + names.map(name => `  ${name}: require('../assets/moment-placeholders/${name}.svg'),`).join('\n') + '\n} as const;\n');
